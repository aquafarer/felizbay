#!/usr/bin/env node
/**
 * scripts/generate-fallback-redirects.mjs
 *
 * Generates dist/_redirects (Cloudflare Pages native, edge-evaluated, no
 * dynamic-rule quota) so that news/rss requests for locales WITHOUT a
 * news-worker zone route 301 to the EN root endpoints instead of 404ing.
 *
 * Both sides are DERIVED, never hand-written (reference: internal request
 * hygiene program — "derive both sides, don't hand-maintain lists"):
 *
 *   - Worker side: parse workers/news-worker/wrangler.toml zone routes →
 *     the locale set whose /xx/news* + /xx/rss.xml are worker-served.
 *   - Locale side: enumerate dist/ language trees, minus worker locales,
 *     minus REMOVED_LOCALES (functions/_middleware.ts owns those with a
 *     prefix-stripping 301 — do not shadow it), minus 'en' (root).
 *
 * Output per fallback locale (4 rules):
 *   /xx/news        /news/        301   (no trailing slash — the edge does
 *                                        NOT auto-append slashes for paths
 *                                        without a static asset)
 *   /xx/news/       /news/        301
 *   /xx/news/*      /news/:splat  301
 *   /xx/rss.xml     /rss.xml      301
 *
 * Self-validation (hard fail on violation):
 *   1. wrangler.toml still declares the ROOT felizbay.com/news* + /rss.xml
 *      routes (otherwise the 301 targets would not be worker-served).
 *   2. Every fallback locale has all four forms; sources are unique.
 *   3. Static rules emitted before splat rules (first-match-wins).
 *   4. No rule shadows a worker-served endpoint (worker locales excluded).
 *   5. REMOVED_LOCALES never appear (middleware is the single owner).
 *   6. Within Pages limits: <= 2100 static, <= 100 dynamic.
 *
 * Idempotent: rewrites dist/_redirects on every build.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIST = path.join(ROOT, 'dist');
const WRANGLER = path.join(ROOT, 'workers', 'news-worker', 'wrangler.toml');
const MIDDLEWARE = path.join(ROOT, 'functions', '_middleware.ts');

const fail = (msg) => {
  console.error(`[fallback-redirects] FAIL: ${msg}`);
  process.exit(1);
};

if (!existsSync(DIST)) fail('dist/ not found — run after astro build');
if (!existsSync(WRANGLER)) fail('workers/news-worker/wrangler.toml not found');
if (!existsSync(MIDDLEWARE)) fail('functions/_middleware.ts not found');

// ---- worker side ----
const toml = readFileSync(WRANGLER, 'utf8');
const workerLocales = new Set([...toml.matchAll(/pattern = "felizbay\.com\/([a-z]{2})\/news\*"/g)].map((m) => m[1]));
if (!/pattern = "felizbay\.com\/news\*"/.test(toml)) {
  fail('wrangler.toml lost its ROOT felizbay.com/news* route — 301 targets would 404');
}
if (!/pattern = "felizbay\.com\/rss\.xml"/.test(toml)) {
  fail('wrangler.toml lost its ROOT felizbay.com/rss.xml route — 301 target would 404');
}
if (workerLocales.size === 0) fail('wrangler.toml declares no /xx/news* routes at all');

// ---- removed locales (middleware owns these — never emit rules for them) ----
const middleware = readFileSync(MIDDLEWARE, 'utf8');
const removedMatch = middleware.match(/const REMOVED_LOCALES\s*=\s*\[([^\]]*)\]/);
if (!removedMatch) fail('cannot parse REMOVED_LOCALES from functions/_middleware.ts');
const removedLocales = new Set([...removedMatch[1].matchAll(/'([a-z]{2})'/g)].map((m) => m[1]));
if (removedLocales.size === 0) fail('REMOVED_LOCALES parsed empty — refusing to emit anything');

// ---- locale side: dist trees ----
const distTrees = new Set(
  readdirSync(DIST, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^[a-z]{2}$/.test(d.name))
    .map((d) => d.name)
);
if (distTrees.size === 0) fail('no language trees in dist/ — run after astro build');

const fallbackLocales = [...distTrees]
  .filter((l) => l !== 'en' && !workerLocales.has(l) && !removedLocales.has(l))
  .sort();

if (fallbackLocales.length === 0) {
  fail('fallback locale set is empty — every dist tree is worker-served or removed; nothing to do (unexpected)');
}

// ---- build rules (static before splat) ----
const lines = [
  '# Auto-generated by scripts/generate-fallback-redirects.mjs -- DO NOT EDIT.',
  `# ${fallbackLocales.length} fallback locales (no news-worker zone route):`,
  `# ${fallbackLocales.join(', ')}`,
  '# /xx/news* + /xx/rss.xml 301 to the EN root endpoints (worker-served).',
  '# REMOVED_LOCALES (zh/ja/ko/vi/hi) are NOT here -- functions/_middleware.ts',
  '# owns them with a prefix-stripping 301.',
  '',
];
const sources = new Set();
let staticCount = 0;
let splatCount = 0;

for (const loc of fallbackLocales) {
  const staticRules = [
    [`/${loc}/news`, '/news/'],
    [`/${loc}/news/`, '/news/'],
    [`/${loc}/rss.xml`, '/rss.xml'],
  ];
  for (const [src, dest] of staticRules) {
    if (sources.has(src)) fail(`duplicate source rule: ${src}`);
    sources.add(src);
    lines.push(`${src} ${dest} 301`);
    staticCount++;
  }
}
for (const loc of fallbackLocales) {
  const src = `/${loc}/news/*`;
  const dest = '/news/:splat';
  if (sources.has(src)) fail(`duplicate source rule: ${src}`);
  sources.add(src);
  lines.push(`${src} ${dest} 301`);
  splatCount++;
}

// ---- limits ----
if (staticCount > 2100) fail(`static rules ${staticCount} exceed the Pages limit (2100)`);
if (splatCount > 100) fail(`dynamic (splat) rules ${splatCount} exceed the Pages limit (100)`);

// ---- shadowing guard: worker endpoints must not be in our source set ----
for (const wl of workerLocales) {
  if (sources.has(`/${wl}/news`)) fail(`rule shadows worker-served endpoint: /${wl}/news`);
}

// ---- write ----
const out = path.join(DIST, '_redirects');
writeFileSync(out, lines.join('\n') + '\n', 'utf8');

console.log(
  `[fallback-redirects] wrote ${out.replace(ROOT, '')}: ${fallbackLocales.length} locales, ` +
    `${staticCount} static + ${splatCount} splat rules (worker: ${[...workerLocales].sort().join(',')}; ` +
    `removed: ${[...removedLocales].sort().join(',')})`
);
